// Generates the MBA mark geometry (rounded polygons) traced from assets/logo-color.webp.
// Run: node scripts/build-mark.mjs  → writes src/components/brand/mark-paths.ts
import { writeFileSync } from 'node:fs'

const sub = (a, b) => [a[0] - b[0], a[1] - b[1]]
const len = (v) => Math.hypot(v[0], v[1])
const norm = (v) => [v[0] / len(v), v[1] / len(v)]
const f = (n) => +n.toFixed(2)

/** Rounded polygon path: pts = [[x, y, r], ...] in drawing order (clockwise). */
function rounded(pts) {
  const n = pts.length
  let d = ''
  pts.forEach((p, i) => {
    const prev = pts[(i - 1 + n) % n], next = pts[(i + 1) % n]
    const r = p[2]
    const v1 = norm(sub(prev, p)), v2 = norm(sub(next, p))
    const ang = Math.acos(v1[0] * v2[0] + v1[1] * v2[1])
    const t = r / Math.tan(ang / 2)
    const a = [p[0] + v1[0] * t, p[1] + v1[1] * t]
    const b = [p[0] + v2[0] * t, p[1] + v2[1] * t]
    const sweep = v1[0] * v2[1] - v1[1] * v2[0] < 0 ? 1 : 0
    d += `${i ? 'L' : 'M'}${f(a[0])} ${f(a[1])}`
    if (r > 0) d += `A${r} ${r} 0 0 ${sweep} ${f(b[0])} ${f(b[1])}`
  })
  return d + 'Z'
}

// Traced vertices (px, origin at the mark's top-left, 794 × 534 box).
const slab = (dx) => [
  [235.5 + dx, 0, 26],
  [311.8 + dx, 0, 22],
  [377 + dx, 160, 6],
  [212 + dx, 534, 26],
  [0 + dx, 534, 26],
]
const A = rounded(slab(0))
const B = rounded(slab(258.5))
const C = rounded([
  [658.3, 212, 30],
  [794, 534, 26],
  [517, 534, 26],
])

writeFileSync(
  'src/components/brand/mark-paths.ts',
  `// Generated by scripts/build-mark.mjs — do not edit by hand.
export const MARK_VIEWBOX = '0 0 794 534'
export const MARK_RATIO = 794 / 534
/** M: the first slanted slab (MZAB). */
export const PATH_M = '${A}'
/** A: the second slab (Alliance). */
export const PATH_A = '${B}'
/** Summit: the rising triangle. */
export const PATH_SUMMIT = '${C}'
`,
)
console.log('ok')
